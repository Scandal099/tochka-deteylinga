/**
 * Builds the scroll image sequence from the 4K source clips.
 *
 *  - every source frame (24 fps) is kept, so scrubbing is smooth
 *  - one shared monochrome grade + light sharpening (lanczos from 4K)
 *  - desktop: 1920x1080, mobile: 1280x720 (portrait screens show the whole car
 *    in a wide band, see getFrameRect in CinematicScroll)
 *  - writes src/data/frames-manifest.ts with the total frame count
 */
import { execFileSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import ffmpegPath from "ffmpeg-static";

if (!ffmpegPath) throw new Error("ffmpeg-static binary path was not found.");

const ORDERED_CLIPS = [
  "Camera_moving_around_Porsche_911_66a2a094_4K.mp4",
  "Camera_filming_car_wheel_ef05b644_4K.mp4",
  "Camera_filming_static_car_9458f8ec_4K.mp4",
  "Porsche_door_opens_to_interior_9372bc52_4K.mp4",
  "Porsche_911_filmed_by_camera_28404cd1_4K.mp4",
  "Camera_orbiting_parked_Porsche_911_e4993bf9_4K.mp4",
];

export const GRADE = "eq=contrast=1.06:saturation=0.78";
const ROOT = process.cwd();
const VIDEO_DIR = path.join(ROOT, "video4k");
const DESKTOP_DIR = path.join(ROOT, "public", "frames", "desktop");
const MOBILE_DIR = path.join(ROOT, "public", "frames", "mobile");
const TMP_DIR = path.join(ROOT, ".tmp-frames");

const VARIANTS = [
  {
    dir: DESKTOP_DIR,
    vf: `scale=1920:1080:flags=lanczos,unsharp=5:5:0.45,${GRADE}`,
    quality: "80",
  },
  {
    dir: MOBILE_DIR,
    vf: `scale=1280:720:flags=lanczos,unsharp=5:5:0.4,${GRADE}`,
    quality: "76",
  },
];

for (const d of [DESKTOP_DIR, MOBILE_DIR, TMP_DIR]) fs.rmSync(d, { recursive: true, force: true });
fs.mkdirSync(DESKTOP_DIR, { recursive: true });
fs.mkdirSync(MOBILE_DIR, { recursive: true });

let globalIndex = 1;

for (let clipIdx = 0; clipIdx < ORDERED_CLIPS.length; clipIdx++) {
  const clipName = ORDERED_CLIPS[clipIdx];
  const clipPath = path.join(VIDEO_DIR, clipName);
  if (!fs.existsSync(clipPath)) throw new Error(`Missing source video: ${clipPath}`);

  const tmpDirs = VARIANTS.map((_, i) => path.join(TMP_DIR, `c${clipIdx}_${i}`));
  tmpDirs.forEach((d) => fs.mkdirSync(d, { recursive: true }));

  // Clips are chained: the first frame of clip N repeats the last frame of clip N-1.
  const skipFirst = clipIdx > 0;

  VARIANTS.forEach((v, i) => {
    execFileSync(
      ffmpegPath,
      [
        "-y",
        "-i",
        clipPath,
        "-vf",
        v.vf,
        "-c:v",
        "libwebp",
        "-quality",
        v.quality,
        "-compression_level",
        "6",
        path.join(tmpDirs[i], "f_%04d.webp"),
      ],
      { stdio: "ignore" }
    );
  });

  const lists = tmpDirs.map((d) => fs.readdirSync(d).sort());
  const count = Math.min(...lists.map((l) => l.length));
  for (let i = skipFirst ? 1 : 0; i < count; i++) {
    const name = `frame_${String(globalIndex).padStart(4, "0")}.webp`;
    VARIANTS.forEach((v, vi) => {
      fs.renameSync(path.join(tmpDirs[vi], lists[vi][i]), path.join(v.dir, name));
    });
    globalIndex++;
  }
  console.log(`Clip ${clipIdx + 1}/${ORDERED_CLIPS.length}: ${clipName} -> ${count - (skipFirst ? 1 : 0)} frames`);
}

fs.rmSync(TMP_DIR, { recursive: true, force: true });

const totalFrames = globalIndex - 1;
fs.writeFileSync(
  path.join(ROOT, "src", "data", "frames-manifest.ts"),
  `// Generated by scripts/extract-frames.mjs — do not edit by hand.\nexport const FRAME_COUNT = ${totalFrames};\n`
);

const dirMB = (d) =>
  +(fs.readdirSync(d).reduce((s, f) => s + fs.statSync(path.join(d, f)).size, 0) / 1048576).toFixed(1);
console.log(JSON.stringify({ totalFrames, desktopMB: dirMB(DESKTOP_DIR), mobileMB: dirMB(MOBILE_DIR) }, null, 2));
